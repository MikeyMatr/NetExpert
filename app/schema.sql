CREATE TABLE IF NOT EXISTS addresses (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 city TEXT NOT NULL, street TEXT NOT NULL, building TEXT NOT NULL, apartment TEXT
);
CREATE TABLE IF NOT EXISTS clients (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name TEXT NOT NULL, phone TEXT
);
CREATE TABLE IF NOT EXISTS tariffs (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name TEXT NOT NULL UNIQUE, speed_mbps INTEGER NOT NULL CHECK (speed_mbps > 0)
);
CREATE TABLE IF NOT EXISTS internet_services (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 client_id BIGINT NOT NULL REFERENCES clients(id),
 address_id BIGINT NOT NULL REFERENCES addresses(id),
 tariff_id BIGINT NOT NULL REFERENCES tariffs(id),
 account_number TEXT NOT NULL UNIQUE, active BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE IF NOT EXISTS router_models (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 manufacturer TEXT NOT NULL, model TEXT NOT NULL,
 UNIQUE (manufacturer, model)
);
CREATE TABLE IF NOT EXISTS routers (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 router_model_id BIGINT NOT NULL REFERENCES router_models(id),
 serial_number TEXT NOT NULL UNIQUE
);
CREATE TABLE IF NOT EXISTS router_rentals (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 service_id BIGINT NOT NULL REFERENCES internet_services(id),
 router_id BIGINT NOT NULL REFERENCES routers(id),
 rented_at TIMESTAMPTZ NOT NULL DEFAULT now(), returned_at TIMESTAMPTZ,
 CHECK (returned_at IS NULL OR returned_at >= rented_at)
);
CREATE TABLE IF NOT EXISTS knowledge_versions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 version_number INTEGER NOT NULL UNIQUE, published_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 is_active BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE UNIQUE INDEX IF NOT EXISTS one_active_knowledge_version
 ON knowledge_versions (is_active) WHERE is_active;
CREATE TABLE IF NOT EXISTS questions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 code TEXT NOT NULL UNIQUE, prompt TEXT NOT NULL, sort_order INTEGER NOT NULL UNIQUE
);
CREATE TABLE IF NOT EXISTS answer_options (
 question_id BIGINT NOT NULL REFERENCES questions(id),
 code TEXT NOT NULL, label TEXT NOT NULL, sort_order INTEGER NOT NULL,
 PRIMARY KEY (question_id, code), UNIQUE (question_id, sort_order)
);
CREATE TABLE IF NOT EXISTS fault_types (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 code TEXT NOT NULL UNIQUE, title TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS production_rules (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 code TEXT NOT NULL UNIQUE,
 knowledge_version_id BIGINT NOT NULL REFERENCES knowledge_versions(id),
 fault_type_id BIGINT NOT NULL REFERENCES fault_types(id),
 priority INTEGER NOT NULL,
 recommendation TEXT NOT NULL,
 explanation TEXT NOT NULL,
 escalation_required BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE TABLE IF NOT EXISTS rule_conditions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 rule_id BIGINT NOT NULL REFERENCES production_rules(id) ON DELETE CASCADE,
 question_id BIGINT NOT NULL,
 answer_code TEXT NOT NULL,
 FOREIGN KEY (question_id, answer_code) REFERENCES answer_options(question_id, code),
 UNIQUE (rule_id, question_id)
);
CREATE TABLE IF NOT EXISTS tickets (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 subscriber_id TEXT NOT NULL,
 service_id BIGINT REFERENCES internet_services(id),
 problem_description TEXT NOT NULL,
 status TEXT NOT NULL DEFAULT 'new'
  CHECK (status IN ('new', 'in_progress', 'resolved', 'escalated')),
 created_by TEXT NOT NULL,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 closed_at TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS tickets_created_idx ON tickets (created_at DESC);
CREATE TABLE IF NOT EXISTS ticket_status_events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 ticket_id BIGINT NOT NULL REFERENCES tickets(id) ON DELETE CASCADE,
 old_status TEXT, new_status TEXT NOT NULL,
 changed_by TEXT NOT NULL, comment TEXT,
 changed_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS diagnostic_sessions (
 id UUID PRIMARY KEY,
 ticket_id BIGINT NOT NULL REFERENCES tickets(id),
 operator_id TEXT NOT NULL,
 knowledge_version_id BIGINT NOT NULL REFERENCES knowledge_versions(id),
 status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'completed')),
 started_at TIMESTAMPTZ NOT NULL DEFAULT now(), finished_at TIMESTAMPTZ,
 matched_rule_code TEXT, suspected_cause TEXT,
 recommendation TEXT, explanation TEXT,
 escalation_required BOOLEAN
);
CREATE TABLE IF NOT EXISTS session_answers (
 session_id UUID NOT NULL REFERENCES diagnostic_sessions(id) ON DELETE CASCADE,
 question_id BIGINT NOT NULL,
 answer_code TEXT NOT NULL,
 step_no INTEGER NOT NULL,
 answered_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 PRIMARY KEY (session_id, question_id),
 UNIQUE (session_id, step_no),
 FOREIGN KEY (question_id, answer_code) REFERENCES answer_options(question_id, code)
);
