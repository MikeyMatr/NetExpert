CREATE TABLE IF NOT EXISTS staff_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    role TEXT NOT NULL CHECK (role IN ('operator', 'expert', 'admin')),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Existing text audit columns stay intact. Historical rows get NULL FKs;
-- all new writes supply verified staff IDs from the authentication dependency.
ALTER TABLE tickets ADD COLUMN IF NOT EXISTS created_by_id BIGINT REFERENCES staff_users(id);
ALTER TABLE tickets ADD COLUMN IF NOT EXISTS assigned_operator_id BIGINT REFERENCES staff_users(id);
ALTER TABLE ticket_status_events ADD COLUMN IF NOT EXISTS changed_by_id BIGINT REFERENCES staff_users(id);
ALTER TABLE diagnostic_sessions ADD COLUMN IF NOT EXISTS operator_user_id BIGINT REFERENCES staff_users(id);

CREATE INDEX IF NOT EXISTS tickets_assigned_operator_idx
    ON tickets (assigned_operator_id, created_at DESC);
